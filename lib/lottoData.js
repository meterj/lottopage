// 번호별 실제 출현 빈도 계산
const buildFrequencyMap = () => {
  const freq = {};
  REAL_LOTTO_DATA.forEach(draw => {
    draw.forEach(n => { freq[n] = (freq[n] || 0) + 1; });
  });
  return freq;
};

export const FREQUENCY_MAP = buildFrequencyMap();

// Hot/Cold 분류: 상위 30%는 HOT, 하위 30%는 COLD
const sorted = Object.entries(FREQUENCY_MAP).sort((a, b) => b[1] - a[1]);
export const HOT_NUMBERS = new Set(sorted.slice(0, 14).map(([n]) => Number(n)));
export const COLD_NUMBERS = new Set(sorted.slice(-14).map(([n]) => Number(n)));
